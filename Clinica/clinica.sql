CREATE DATABASE IF NOT EXISTS clinica CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE clinica;
CREATE TABLE IF NOT EXISTS Pacientes (
 paciente_id INT AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL,
 apellido VARCHAR(100) NOT NULL,
 direccion VARCHAR(200) NOT NULL,
 telefono VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS Medicos (
 medico_id INT AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL,
 especialidad VARCHAR(100) NOT NULL,
 telefono VARCHAR(30) NOT NULL,
 email VARCHAR(150) NOT NULL
);
CREATE TABLE IF NOT EXISTS consultas (
 consulta_id INT AUTO_INCREMENT PRIMARY KEY,
 paciente_id INT NOT NULL,
 medico_id INT NOT NULL,
 fecha DATETIME NOT NULL,
 motivo VARCHAR(255) NOT NULL,
 FOREIGN KEY (paciente_id) REFERENCES Pacientes(paciente_id) ON DELETE RESTRICT,
 FOREIGN KEY (medico_id) REFERENCES Medicos(medico_id) ON DELETE RESTRICT
);
